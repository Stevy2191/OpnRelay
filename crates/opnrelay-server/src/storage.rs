//! Encrypted object storage on the local filesystem.

use std::path::{Path, PathBuf};
use std::sync::Arc;

use anyhow::{Context, Result};
use opnrelay_crypto::SecretKey;
use time::OffsetDateTime;
use uuid::Uuid;

#[derive(Clone)]
pub struct Storage {
    root: PathBuf,
    kek: Arc<SecretKey>,
}

/// What must be persisted in the `media` row to read the object back.
pub struct StoredObject {
    pub storage_key: String,
    pub dek_wrapped: Vec<u8>,
    pub kek_id: String,
}

impl Storage {
    pub fn new(root: PathBuf, kek: SecretKey) -> Self {
        Self {
            root,
            kek: Arc::new(kek),
        }
    }

    pub fn kek_id(&self) -> String {
        self.kek.key_id()
    }

    fn path_for(&self, key: &str) -> Result<PathBuf> {
        // Keys are generated by us, but defend against traversal anyway.
        if key
            .split('/')
            .any(|p| p.is_empty() || p == "." || p == "..")
        {
            anyhow::bail!("invalid storage key");
        }
        Ok(self.root.join(key))
    }

    pub async fn ensure_root(&self) -> Result<()> {
        tokio::fs::create_dir_all(&self.root)
            .await
            .with_context(|| format!("creating storage dir {}", self.root.display()))
    }

    /// Check that the storage directory is writable.
    pub async fn health(&self) -> bool {
        tokio::fs::metadata(&self.root)
            .await
            .map(|m| m.is_dir())
            .unwrap_or(false)
    }

    /// Encrypt and write `plaintext` for object `id`.
    pub async fn put(&self, prefix: &str, id: Uuid, plaintext: Vec<u8>) -> Result<StoredObject> {
        let now = OffsetDateTime::now_utc();
        let key = format!(
            "{prefix}/{:04}/{:02}/{id}",
            now.year(),
            u8::from(now.month())
        );
        let path = self.path_for(&key)?;
        let kek = self.kek.clone();
        let aad = id.as_bytes().to_vec();
        let env = tokio::task::spawn_blocking(move || {
            opnrelay_crypto::envelope_seal(&kek, &plaintext, &aad)
        })
        .await??;
        write_atomic(&path, &env.ciphertext).await?;
        Ok(StoredObject {
            storage_key: key,
            dek_wrapped: env.wrapped_dek,
            kek_id: self.kek.key_id(),
        })
    }

    /// Read and decrypt an object.
    pub async fn get(&self, id: Uuid, storage_key: &str, dek_wrapped: &[u8]) -> Result<Vec<u8>> {
        let path = self.path_for(storage_key)?;
        let ct = tokio::fs::read(&path)
            .await
            .with_context(|| format!("reading object {storage_key}"))?;
        let kek = self.kek.clone();
        let wrapped = dek_wrapped.to_vec();
        let aad = id.as_bytes().to_vec();
        let pt = tokio::task::spawn_blocking(move || {
            opnrelay_crypto::envelope_open(&kek, &wrapped, &ct, &aad)
        })
        .await??;
        Ok(pt)
    }

    pub async fn delete(&self, storage_key: &str) -> Result<()> {
        let path = self.path_for(storage_key)?;
        match tokio::fs::remove_file(&path).await {
            Ok(()) => Ok(()),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
            Err(e) => Err(e.into()),
        }
    }
}

async fn write_atomic(path: &Path, data: &[u8]) -> Result<()> {
    let dir = path.parent().context("object path has a parent")?;
    tokio::fs::create_dir_all(dir).await?;
    let tmp = dir.join(format!(".tmp-{}", Uuid::now_v7()));
    tokio::fs::write(&tmp, data).await?;
    tokio::fs::rename(&tmp, path).await?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[tokio::test]
    async fn put_get_roundtrip_encrypted_on_disk() {
        let dir = std::env::temp_dir().join(format!("opnrelay-test-{}", Uuid::now_v7()));
        let s = Storage::new(dir.clone(), SecretKey::generate());
        let id = Uuid::now_v7();
        let obj = s.put("media", id, b"secret pixels".to_vec()).await.unwrap();
        let raw = tokio::fs::read(dir.join(&obj.storage_key)).await.unwrap();
        assert!(!raw.windows(6).any(|w| w == b"secret"), "stored encrypted");
        let back = s.get(id, &obj.storage_key, &obj.dek_wrapped).await.unwrap();
        assert_eq!(back, b"secret pixels");
        assert!(
            s.get(Uuid::now_v7(), &obj.storage_key, &obj.dek_wrapped)
                .await
                .is_err()
        );
        assert!(s.path_for("../etc/passwd").is_err());
        s.delete(&obj.storage_key).await.unwrap();
        let _ = tokio::fs::remove_dir_all(dir).await;
    }
}
